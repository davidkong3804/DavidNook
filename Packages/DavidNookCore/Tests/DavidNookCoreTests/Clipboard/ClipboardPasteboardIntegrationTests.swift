    // MARK: 輪詢行為

    func testPollingOnlyReadsContentWhenChangeCountChanged() async {
        let rig = makeRig()
        await rig.monitor.start()
        for i in 0..<5 { await rig.monitor.pollOnce(now: t(Double(i))) }
        XCTAssertEqual(rig.reader.snapshotCalls, 0)
        externalCopy([(PBType.utf8Text, bytes("changed"))])
        for i in 5..<10 { await rig.monitor.pollOnce(now: t(Double(i))) }
        XCTAssertEqual(rig.reader.snapshotCalls, 1)
    }

    func testRealTimerEndToEndRecordsNewCopyWithinAFewTicks() async throws {
        let rig = makeRig(scheduler: TaskClipboardScheduler(), interval: 0.02)
        await rig.monitor.start()
        externalCopy([(PBType.utf8Text, bytes("end to end"))])
        var recorded: [String] = []
        for _ in 0..<250 where recorded.isEmpty {
            try await Task.sleep(nanoseconds: 20_000_000)
            recorded = await rig.store.items.compactMap(\.text)
        }
        await rig.monitor.stop()
        XCTAssertEqual(recorded, ["end to end"])
    }

    // MARK: 寫回

    func testWriteBackTextRoundTripsAndIsNotRecordedAgain() async throws {
        let rig = makeRig()
        await rig.monitor.start()
        externalCopy([(PBType.utf8Text, bytes("original"))])
        await rig.monitor.pollOnce(now: t(1))
        let item = try await firstItem(rig.store)

        // 使用者在別處複製了其他東西，之後從歷史點選「original」貼回
        externalCopy([(PBType.utf8Text, bytes("something else"))])
        await rig.monitor.pollOnce(now: t(2))
        let writer = NSPasteboardWriter(pasteboard: pasteboard)
        let new = try await rig.monitor.writeBack(item: item, to: writer, now: t(3))

        XCTAssertEqual(new, pasteboard.changeCount)
        XCTAssertEqual(pasteboard.string(forType: .string), "original")
        XCTAssertNotNil(pasteboard.data(forType: NSPasteboard.PasteboardType(PBType.selfMarker)))
        let callsBefore = rig.reader.snapshotCalls
        await rig.monitor.pollOnce(now: t(4))
        XCTAssertEqual(rig.reader.snapshotCalls, callsBefore, "自己寫回的內容不會再被讀取")
        let order = await rig.store.items.compactMap(\.text)
        XCTAssertEqual(order, ["original", "something else"], "點選的條目被 bump 到最前面，且沒有新增重複條目")
    }

    func testWriteBackImageAndFilesRoundTripOnRealPasteboard() async throws {
        let rig = makeRig()
        await rig.monitor.start()
        externalCopy([(PBType.png, tinyPNG)])
        await rig.monitor.pollOnce(now: t(1))
        pasteboard.clearContents()
        XCTAssertTrue(pasteboard.writeObjects([NSURL(fileURLWithPath: "/Users/example/x.txt"), NSURL(fileURLWithPath: "/Users/example/y.txt")]))
        await rig.monitor.pollOnce(now: t(2))
        let items = await rig.store.items
        let image = try XCTUnwrap(items.first { $0.kind == .image })
        let files = try XCTUnwrap(items.first { $0.kind == .files })
        let writer = NSPasteboardWriter(pasteboard: pasteboard)

        _ = try await rig.monitor.writeBack(item: image, to: writer, now: t(3))
        XCTAssertEqual(pasteboard.data(forType: .png), tinyPNG)

        _ = try await rig.monitor.writeBack(item: files, to: writer, now: t(4))
        let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: nil) as? [URL]
        XCTAssertEqual(urls?.map(\.path), ["/Users/example/x.txt", "/Users/example/y.txt"])
        await rig.monitor.pollOnce(now: t(5))
        let count = await rig.store.items.count
        XCTAssertEqual(count, 2, "寫回不產生新條目")
    }

    // MARK: macOS 對具名剪貼簿的存取行為

    func testNamedPasteboardAccessBehaviorDoesNotRequireAPrompt() throws {
        guard #available(macOS 15.4, *) else { throw XCTSkip("accessBehavior 需要 macOS 15.4+") }
        // 標頭文件：具名（非 general）剪貼簿預設即「永遠允許」，程式化存取不會跳提示。
        // 因此這個整合測試無法驗證「系統剪貼簿」在 macOS 27 是否會跳提示（那需要碰系統剪貼簿，被禁止）。
        let behavior = pasteboard.accessBehavior
        XCTAssertTrue(behavior == .default || behavior == .alwaysAllow, "實際為 \(behavior.rawValue)")
    }
