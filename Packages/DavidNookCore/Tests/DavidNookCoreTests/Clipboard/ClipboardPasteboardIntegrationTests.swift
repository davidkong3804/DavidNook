import AppKit
import XCTest
@testable import DavidNookCore

/// 元件 7：以「真實 NSPasteboard」做整合測試。
/// 只使用 NamedPasteboardTestCase 建立的具名剪貼簿（每個測試一個獨立名稱，tearDown 釋放），不碰系統剪貼簿。
final class ClipboardPasteboardIntegrationTests: NamedPasteboardTestCase {
    /// 包住真實 reader，計算 snapshot() 被呼叫的次數。
    private final class CountingReader: PasteboardReading, @unchecked Sendable {
        let inner: NSPasteboardReader
        private let lock = NSLock()
        private var calls = 0
        init(_ inner: NSPasteboardReader) { self.inner = inner }
        var snapshotCalls: Int { lock.withLock { calls } }
        var changeCount: Int { inner.changeCount }
        func snapshot() -> PasteboardSnapshot {
            lock.withLock { calls += 1 }
            return inner.snapshot()
        }
    }

    private struct Rig {
        let monitor: ClipboardMonitor
        let store: ClipboardStore
        let reader: CountingReader
    }

    private func makeRig(scheduler: ClipboardScheduler = ManualClipboardScheduler(), interval: TimeInterval = 0.5) -> Rig {
        let reader = CountingReader(NSPasteboardReader(pasteboard: pasteboard, sourceAppProvider: { "com.example.frontmost" }))
        let store = ClipboardStore(persistence: InMemoryClipboardPersistence())
        let monitor = ClipboardMonitor(reader: reader, store: store, scheduler: scheduler, interval: interval)
        return Rig(monitor: monitor, store: store, reader: reader)
    }

    private func bytes(_ string: String) -> Data { Data(string.utf8) }

    private func firstItem(_ store: ClipboardStore) async throws -> ClipboardItem {
        let items = await store.items
        return try XCTUnwrap(items.first)
    }

    // MARK: 隱私型別

    func testConcealedTextOnRealPasteboardIsNotRecorded() async {
        let rig = makeRig()
        await rig.monitor.start()
        externalCopy([(PBType.utf8Text, bytes("hunter2")), (PBType.concealed, bytes("1"))])
        await rig.monitor.pollOnce(now: t(1))
        let items = await rig.store.items
        XCTAssertTrue(items.isEmpty)
    }

    func testConcealedMarkerWithEmptyDataIsStillDetectedOnRealPasteboard() async {
        // 許多密碼管理員只宣告型別、資料為空；NSPasteboard 必須仍然把這個型別列出來。
        let rig = makeRig()
        await rig.monitor.start()
        externalCopy([(PBType.utf8Text, bytes("hunter2")), (PBType.concealed, Data())])
        await rig.monitor.pollOnce(now: t(1))
        let items = await rig.store.items
        XCTAssertTrue(items.isEmpty)
    }

    func testTransientAutoGeneratedAndLegacyMarkersAreNotRecordedOnRealPasteboard() async {
        let rig = makeRig()
        await rig.monitor.start()
        let markers = [
            PBType.transient, PBType.autoGenerated, PBType.onePassword, PBType.petermaurerTransient,
            PBType.typeIt4MeClipping,
        ]
        for (i, type) in markers.enumerated() {
            externalCopy([(PBType.utf8Text, bytes("secret-\(i)")), (type, bytes("1"))])
            await rig.monitor.pollOnce(now: t(Double(i)))
        }
        let items = await rig.store.items
        XCTAssertEqual(items.compactMap(\.text), [], "不得有任何標記型別的內容被記錄（測試資料為自編字串）")
    }

    /// Typinator 的標記 "Pasteboard generator type" 不是合法的 UTI（含空白）。實測（具名剪貼簿）：
    /// 用 `NSPasteboardItem.setData` 寫入時型別會直接消失；用舊式 `declareTypes`／`setData(forType:)` 寫入時，
    /// `NSPasteboard.types` 會同時列出原字串與一個 `dyn.` 動態 UTI。reader 收集了 `pasteboard.types`，所以舊式寫法可被偵測。
    func testTypinatorLegacyMarkerDeclaredTheOldWayIsNotRecordedOnRealPasteboard() async {
        let rig = makeRig()
        await rig.monitor.start()
        let marker = NSPasteboard.PasteboardType(PBType.typinatorGenerator)
        pasteboard.clearContents()
        pasteboard.declareTypes([.string, marker], owner: nil)
        pasteboard.setString("secret-typinator", forType: .string)
        pasteboard.setData(bytes("1"), forType: marker)
        await rig.monitor.pollOnce(now: t(1))
        let items = await rig.store.items
        XCTAssertEqual(items.compactMap(\.text), [], "Typinator 的 generator 標記必須被略過")
    }

    // MARK: reader 層：被略過的快照不讀內容（F7a）

    /// 讓 reader 把「每次真的向 NSPasteboard 讀資料」回報給計數器，證明敏感快照在 reader 層就沒有讀任何資料。
    private func makeObservedReader(_ counter: DataReadCounter) -> NSPasteboardReader {
        NSPasteboardReader(
            pasteboard: pasteboard,
            sourceAppProvider: { "com.example.frontmost" },
            dataReadObserver: { counter.record($0) }
        )
    }

    func testControlRecordingPlainTextDoesReadDataSoTheReaderCounterIsNotVacuous() {
        let counter = DataReadCounter()
        let reader = makeObservedReader(counter)
        externalCopy([(PBType.utf8Text, bytes("plain text"))])
        let decision = ClipboardPolicy().evaluate(reader.snapshot())
        XCTAssertEqual(decision, .record(ClipboardCapture(text: "plain text", sourceAppBundleID: "com.example.frontmost")))
        XCTAssertTrue(counter.readTypes.contains(PBType.utf8Text), "對照組：要記錄的內容一定會讀資料；實際讀了 \(counter.readTypes)")
    }

    func testSensitiveSnapshotsReadNoPasteboardDataAtTheReaderLayer() {
        let counter = DataReadCounter()
        let reader = makeObservedReader(counter)
        let policy = ClipboardPolicy()
        // item.setData 寫得進去的標記型別（Typinator 的型別含空白，另測舊式寫法）
        for marker in PBType.defaultIgnored where marker != PBType.typinatorGenerator {
            externalCopy([(PBType.utf8Text, bytes("secret")), (PBType.png, tinyPNG), (PBType.fileURL, bytes("file:///secret")), (marker, bytes("1"))])
            XCTAssertEqual(policy.evaluate(reader.snapshot()), .skip(.sensitiveType), marker)
            XCTAssertEqual(counter.readTypes, [], "\(marker)：敏感快照在 reader 層不得讀取任何資料")
        }

        let typinator = NSPasteboard.PasteboardType(PBType.typinatorGenerator)
        pasteboard.clearContents()
        pasteboard.declareTypes([.string, typinator], owner: nil)
        pasteboard.setString("secret", forType: .string)
        pasteboard.setData(bytes("1"), forType: typinator)
        XCTAssertEqual(policy.evaluate(reader.snapshot()), .skip(.sensitiveType))
        XCTAssertEqual(counter.readTypes, [], "Typinator 標記：同樣不得讀取任何資料")
    }

    func testMonitorPollingASensitiveCopyReadsNoPasteboardDataAtTheReaderLayer() async {
        let counter = DataReadCounter()
        let store = ClipboardStore(persistence: InMemoryClipboardPersistence())
        let monitor = ClipboardMonitor(reader: makeObservedReader(counter), store: store, scheduler: ManualClipboardScheduler())
        await monitor.start()
        externalCopy([(PBType.utf8Text, bytes("hunter2")), (PBType.concealed, Data())])
        await monitor.pollOnce(now: t(1))
        let items = await store.items
        XCTAssertTrue(items.isEmpty)
        XCTAssertEqual(counter.readTypes, [], "monitor 輪詢到機密複製時，reader 一個位元組都不能讀")
    }

